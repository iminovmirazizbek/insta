def _whitenoise_headers(headers, path, url):
    # Vite puts a content hash in /assets/ file names, so those can be cached forever.
    # Everything else (index.html, manifest, icons, sw.js) must always be revalidated,
    # otherwise a stale index.html points to hashed files that no longer exist.
    if '/assets/' in url:
        headers['Cache-Control'] = 'public, max-age=31536000, immutable'
    else:
        headers['Cache-Control'] = 'no-cache'


WHITENOISE_ADD_HEADERS_FUNCTION = _whitenoise_headers


